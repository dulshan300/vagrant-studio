use serde::Serialize;

/// A built-in starting point for a new project's Vagrantfile.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Template {
    pub id: &'static str,
    pub name: &'static str,
    pub description: &'static str,
    pub machines: &'static [&'static str],
    #[serde(skip)]
    pub vagrantfile: &'static str,
}

/// Templates are validated with `vagrant validate` (see docs/implementation-status.md).
pub const TEMPLATES: &[Template] = &[
    Template {
        id: "single-linux-vm",
        name: "Single Linux VM",
        description: "One Ubuntu 24.04 machine with common build tools.",
        machines: &["default"],
        vagrantfile: include_str!("../../../templates/single-linux-vm/Vagrantfile"),
    },
    Template {
        id: "web-database",
        name: "Web + database",
        description: "An nginx web server and a PostgreSQL server on a private network.",
        machines: &["web", "db"],
        vagrantfile: include_str!("../../../templates/web-database/Vagrantfile"),
    },
    Template {
        id: "multi-tier-app",
        name: "Multi-tier application",
        description: "Reverse proxy, application server and database on a private network.",
        machines: &["proxy", "app", "db"],
        vagrantfile: include_str!("../../../templates/multi-tier-app/Vagrantfile"),
    },
];

pub fn find(id: &str) -> Option<&'static Template> {
    TEMPLATES.iter().find(|t| t.id == id)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn templates_are_marked_and_define_their_machines() {
        for t in TEMPLATES {
            assert!(
                t.vagrantfile.contains("Generated by Vagrant Studio"),
                "{}",
                t.id
            );
            assert!(
                t.vagrantfile.contains("Vagrant.configure(\"2\")"),
                "{}",
                t.id
            );
            if t.machines.len() > 1 {
                for m in t.machines {
                    assert!(
                        t.vagrantfile.contains(&format!("config.vm.define \"{m}\"")),
                        "{} missing {m}",
                        t.id
                    );
                }
            }
        }
        assert!(find("web-database").is_some());
        assert!(find("nope").is_none());
    }
}
